//! Renders the CRD into the Helm chart template that `crdgen` writes and
//! `tests/crd_drift.rs` checks.

use std::fmt::Write as _;

use serde_json::Value;

use super::AgentAccessPolicy;

/// The chart template, relative to the crate root.
pub const CHART_PATH: &str =
    "charts/kagent-gateway/templates/crds/agentaccesspolicies.access.kagent-gateway.sh.yaml";

const METADATA: &str = r#"  labels:
    {{- include "kagent-gateway.labels" . | nindent 4 }}
    {{- with .Values.crds.additionalLabels }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- if or .Values.crds.keep .Values.crds.annotations }}
  annotations:
    {{- if .Values.crds.keep }}
    helm.sh/resource-policy: keep
    {{- end }}
    {{- with .Values.crds.annotations }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- end }}
"#;

const FOOTER: &str = "{{- end }}\n";

/// Folds the line breaks of wrapped `///` comments into single spaces. They
/// carry no meaning in a schema description.
fn collapse_descriptions(node: &mut Value) {
    match node {
        Value::Object(map) => {
            for (key, value) in map.iter_mut() {
                match value {
                    Value::String(s) if key == "description" => {
                        *s = s.split_whitespace().collect::<Vec<_>>().join(" ");
                    }
                    _ => collapse_descriptions(value),
                }
            }
        }
        Value::Array(items) => items.iter_mut().for_each(collapse_descriptions),
        _ => {}
    }
}

/// The chart template: the generated `spec` verbatim, with Helm owning the
/// metadata.
pub fn render() -> String {
    let crd = AgentAccessPolicy::definition();
    let name = crd.metadata.name.clone().unwrap_or_default();
    let mut spec = serde_json::to_value(&crd.spec).expect("a CRD spec serializes");
    collapse_descriptions(&mut spec);
    let body = serde_yaml::to_string(&serde_json::json!({ "spec": spec }))
        .expect("a JSON value serializes as YAML");

    let mut out = String::new();
    let _ = write!(
        out,
        "{{{{- if .Values.crds.install }}}}
{{{{- /*
  Generated by `make crd` from AgentAccessPolicySpec. Do not edit:
  change the Rust type and regenerate.

  This sits in templates/ rather than crds/ because Helm never upgrades anything
  in crds/, so a schema change there would silently not apply.
*/}}}}
apiVersion: apiextensions.k8s.io/v1
kind: CustomResourceDefinition
metadata:
  name: {name}
"
    );
    out.push_str(METADATA);
    out.push_str(&body);
    out.push_str(FOOTER);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_wraps_the_generated_spec() {
        let out = render();
        assert!(out.starts_with("{{- if .Values.crds.install }}\n{{- /*\n"));
        assert!(out.ends_with("{{- end }}\n"));
        assert!(
            out.contains("  name: agentaccesspolicies.access.kagent-gateway.sh\n"),
            "{out}"
        );
        assert!(out.contains("\nspec:\n  group: access.kagent-gateway.sh\n"));
        assert!(out.contains("self.metadata.name == self.spec.agentRef.name"));
        assert!(CHART_PATH.ends_with("agentaccesspolicies.access.kagent-gateway.sh.yaml"));
    }

    #[test]
    fn descriptions_lose_their_line_breaks() {
        let mut v = serde_json::json!({
            "description": "one\n two",
            "items": [{"description": "a\nb"}],
            "nested": {"description": "x  y", "other": "keep\nthis"}
        });
        collapse_descriptions(&mut v);
        assert_eq!(v["description"], "one two");
        assert_eq!(v["items"][0]["description"], "a b");
        assert_eq!(v["nested"]["description"], "x y");
        assert_eq!(v["nested"]["other"], "keep\nthis");
    }
}
