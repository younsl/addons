//! Renders each CRD into the Helm chart template that `crdgen` writes and
//! `tests/crd_drift.rs` checks.

use std::fmt::Write as _;

use serde_json::Value;

use super::CrdKind;

/// The directory of the chart's CRD templates, relative to the crate root.
pub const CHART_CRD_DIR: &str = "charts/volume-autoscaler/templates/crds";

const METADATA: &str = r#"  labels:
    {{- include "volume-autoscaler.labels" . | nindent 4 }}
    {{- with .Values.crds.additionalLabels }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- if or .Values.crds.keep .Values.crds.annotations }}
  annotations:
    {{- if .Values.crds.keep }}
    helm.sh/resource-policy: keep
    {{- end }}
    {{- with .Values.crds.annotations }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- end }}
"#;

const FOOTER: &str = "{{- end }}\n";

/// Folds the line breaks of wrapped `///` comments into single spaces. They
/// carry no meaning in a schema description.
fn collapse_descriptions(node: &mut Value) {
    match node {
        Value::Object(map) => {
            for (key, value) in map.iter_mut() {
                match value {
                    Value::String(s) if key == "description" => {
                        *s = s.split_whitespace().collect::<Vec<_>>().join(" ");
                    }
                    _ => collapse_descriptions(value),
                }
            }
        }
        Value::Array(items) => items.iter_mut().for_each(collapse_descriptions),
        _ => {}
    }
}

/// The chart template of `kind`, relative to the crate root.
#[must_use]
pub fn chart_path(kind: CrdKind) -> String {
    let name = kind.crd().metadata.name.unwrap_or_default();
    format!("{CHART_CRD_DIR}/{name}.yaml")
}

/// The chart template of `kind`: the generated `spec` verbatim, with Helm
/// owning the metadata (the chart labels and the operator's annotations).
///
/// # Panics
///
/// Never in practice: a derived CRD always serializes.
#[must_use]
pub fn render(kind: CrdKind) -> String {
    let crd = kind.crd();
    let name = crd.metadata.name.clone().unwrap_or_default();
    let mut spec = serde_json::to_value(&crd.spec).expect("a CRD spec serializes");
    collapse_descriptions(&mut spec);
    let body = serde_yaml::to_string(&serde_json::json!({ "spec": spec }))
        .expect("a JSON value serializes as YAML");

    let mut out = String::new();
    let _ = write!(
        out,
        "{{{{- if .Values.crds.install }}}}
{{{{- /*
  Generated by `make crd` from {kind}Spec. Do not edit:
  change the Rust type and regenerate.

  This sits in templates/ rather than crds/ because Helm never upgrades anything
  in crds/. A schema change there would silently not apply, and this chart is
  installed through Argo CD, where that failure is invisible.
*/}}}}
apiVersion: apiextensions.k8s.io/v1
kind: CustomResourceDefinition
metadata:
  name: {name}
",
        kind = crd.spec.names.kind,
    );
    out.push_str(METADATA);
    out.push_str(&body);
    out.push_str(FOOTER);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_wraps_the_generated_spec() {
        let out = render(CrdKind::PersistentVolumeClaimAutoscaler);
        assert!(out.starts_with("{{- if .Values.crds.install }}\n{{- /*\n"));
        assert!(
            out.contains("from PersistentVolumeClaimAutoscalerSpec."),
            "{out}"
        );
        assert!(out.ends_with("{{- end }}\n"));
        assert!(
            out.contains(
                "  name: persistentvolumeclaimautoscalers.autoscaling.volume-autoscaler.sh\n"
            ),
            "{out}"
        );
        assert!(out.contains("\nspec:\n  group: autoscaling.volume-autoscaler.sh\n"));
        assert_eq!(
            chart_path(CrdKind::InstanceVolumeAutoscaler),
            "charts/volume-autoscaler/templates/crds/instancevolumeautoscalers.autoscaling.volume-autoscaler.sh.yaml"
        );
    }

    #[test]
    fn descriptions_lose_their_line_breaks() {
        let mut v = serde_json::json!({
            "description": "one\n two",
            "items": [{"description": "a\nb"}],
            "nested": {"description": "x  y", "other": "keep\nthis"}
        });
        collapse_descriptions(&mut v);
        assert_eq!(v["description"], "one two");
        assert_eq!(v["items"][0]["description"], "a b");
        assert_eq!(v["nested"]["description"], "x y");
        assert_eq!(v["nested"]["other"], "keep\nthis");
    }
}
