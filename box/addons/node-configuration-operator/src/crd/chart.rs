//! Renders the `NodeConfiguration` CRD into the Helm chart template that `crdgen`
//! writes and `tests/crd_drift.rs` checks.

use std::fmt::Write as _;

use k8s_openapi::apiextensions_apiserver::pkg::apis::apiextensions::v1::CustomResourceDefinition;
use kube::CustomResourceExt as _;
use serde_json::Value;

use super::NodeConfiguration;
use super::binding::NodeConfigurationBinding;

const CRD_DIR: &str = "charts/node-configuration-operator/templates/crds";

const HEADER: &str = r"{{- if .Values.crds.install }}
{{- /*
  Generated by `make crd` from the Rust types. Do not edit:
  change the type and regenerate.

  This sits in templates/ rather than crds/ because Helm never upgrades anything
  in crds/, so a schema change there would silently not apply.
*/}}
apiVersion: apiextensions.k8s.io/v1
kind: CustomResourceDefinition
metadata:
";

const METADATA: &str = r#"  labels:
    {{- include "node-configuration-operator.labels" . | nindent 4 }}
    {{- with .Values.crds.additionalLabels }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- if or .Values.crds.keep .Values.crds.annotations }}
  annotations:
    {{- if .Values.crds.keep }}
    helm.sh/resource-policy: keep
    {{- end }}
    {{- with .Values.crds.annotations }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
  {{- end }}
"#;

const FOOTER: &str = "{{- end }}\n";

/// Folds the line breaks of wrapped `///` comments into single spaces. They
/// carry no meaning in a schema description.
fn collapse_descriptions(node: &mut Value) {
    match node {
        Value::Object(map) => {
            for (key, value) in map.iter_mut() {
                match value {
                    Value::String(s) if key == "description" => {
                        *s = s.split_whitespace().collect::<Vec<_>>().join(" ");
                    }
                    _ => collapse_descriptions(value),
                }
            }
        }
        Value::Array(items) => items.iter_mut().for_each(collapse_descriptions),
        _ => {}
    }
}

/// One chart template: the generated `spec` verbatim, with Helm owning the
/// metadata (the chart labels and the operator's annotations).
fn render(crd: &CustomResourceDefinition) -> String {
    let name = crd.metadata.name.clone().unwrap_or_default();
    let mut spec = serde_json::to_value(&crd.spec).expect("a CRD spec serializes");
    collapse_descriptions(&mut spec);
    // The API server drops an empty list, which Argo CD would show as drift.
    if let Some(names) = spec.get_mut("names").and_then(Value::as_object_mut)
        && names
            .get("categories")
            .and_then(Value::as_array)
            .is_some_and(Vec::is_empty)
    {
        names.remove("categories");
    }
    let body = serde_yaml::to_string(&serde_json::json!({ "spec": spec }))
        .expect("a JSON value serializes as YAML");

    let mut out = String::from(HEADER);
    let _ = writeln!(out, "  name: {name}");
    out.push_str(METADATA);
    out.push_str(&body);
    out.push_str(FOOTER);
    out
}

/// Every chart CRD template as its path, relative to the crate root, and its
/// content.
#[must_use]
pub fn templates() -> Vec<(String, String)> {
    [NodeConfiguration::crd(), NodeConfigurationBinding::crd()]
        .iter()
        .map(|crd| {
            let name = crd.metadata.name.clone().unwrap_or_default();
            (format!("{CRD_DIR}/{name}.yaml"), render(crd))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn templates_wrap_the_generated_specs() {
        let templates = templates();
        let paths: Vec<&str> = templates.iter().map(|(path, _)| path.as_str()).collect();
        assert_eq!(
            paths,
            [
                "charts/node-configuration-operator/templates/crds/nodeconfigurations.node-configuration-operator.sh.yaml",
                "charts/node-configuration-operator/templates/crds/nodeconfigurationbindings.node-configuration-operator.sh.yaml",
            ]
        );
        let out = &templates[0].1;
        assert!(out.starts_with("{{- if .Values.crds.install }}\n"));
        assert!(out.ends_with("{{- end }}\n"));
        assert!(
            out.contains("  name: nodeconfigurations.node-configuration-operator.sh\n"),
            "{out}"
        );
        assert!(
            out.contains("\nspec:\n  group: node-configuration-operator.sh\n"),
            "{out}"
        );
        assert!(out.contains("- nc\n"), "{out}");
        assert!(out.contains("scope: Cluster"), "{out}");
        assert!(!out.contains("categories"), "{out}");
        assert!(templates[1].1.contains("- ncb\n"));
    }

    #[test]
    fn descriptions_lose_their_line_breaks() {
        let mut v = serde_json::json!({
            "description": "one\n two",
            "items": [{"description": "a\nb"}],
            "nested": {"description": "x  y", "other": "keep\nthis"}
        });
        collapse_descriptions(&mut v);
        assert_eq!(v["description"], "one two");
        assert_eq!(v["items"][0]["description"], "a b");
        assert_eq!(v["nested"]["description"], "x y");
        assert_eq!(v["nested"]["other"], "keep\nthis");
    }
}
