import { toPascalCase } from "../naming.mjs";

function generatedHeader(spec) {
  return `// This file is generated by scripts/openapi-query-options.mjs.
// Source: src/openapi/openapi.yaml (repository root)
// OpenAPI: ${spec.info?.title ?? "API"} ${spec.info?.version ?? ""}

`;
}

function renderKeyFunction(operation) {
  const args = operation.argsType
    ? `(params${operation.argsRequired}: ${operation.typeName}Request)`
    : "()";
  if (!operation.argsType) {
    return `  ${operation.name}: () => key("GET", "${operation.routePath}"),`;
  }

  return `  ${operation.name}: ${args} =>
    key("GET", "${operation.routePath}", params),`;
}

function renderQueryOptionFunction(operation) {
  const args = operation.argsType
    ? `(params${operation.argsRequired}: ${operation.typeName}Request)`
    : "()";
  const keyArgs = operation.argsType ? "params" : "";
  const paramsArg = operation.argsRequired === "?" ? "params ?? {}" : "params";
  const serviceArgs = operation.argsType
    ? `${paramsArg}, { signal, client }`
    : "{ signal, client }";

  return `    ${operation.name}: ${args} =>
      queryOptions({
        queryKey: openApiQueryKeys.${operation.name}(${keyArgs}),
        queryFn: ({ signal }) =>
          ${operation.name}(${serviceArgs}),
      }),`;
}

export function renderQueryKeysFile(spec, operations) {
  const keys = operations.map(renderKeyFunction).join("\n");
  return `${generatedHeader(spec)}${renderRequestTypeImports(operations)}
export type OpenApiQueryKeyParams = {
  path?: Record<string, string | number | boolean>;
  query?: Record<string, string | number | boolean | null | undefined>;
};

function key(method: string, routePath: string, params?: OpenApiQueryKeyParams) {
  return ["openapi", method, routePath, params ?? {}] as const;
}

export const openApiQueryKeys = {
${keys}
} as const;
`;
}

export function renderDomainQueryOptionsFile(spec, domain, operations) {
  const options = operations.map(renderQueryOptionFunction).join("\n");
  const serviceImports = renderServiceImports(domain, operations);
  const requestTypeImports = renderRequestTypeImports(operations);
  const factoryName = `create${toPascalCase(domain)}OpenApiQueryOptions`;

  return `${generatedHeader(spec)}import { queryOptions } from "@tanstack/react-query";

import { type HttpClient } from "@/lib/http/client/http-client";
import { openApiQueryKeys } from "@/query/v1/openapi-query-keys";
${serviceImports}
${requestTypeImports}
export function ${factoryName}(client: HttpClient) {
  return {
${options}
  } as const;
}
`;
}

export function renderQueryOptionsFile(spec, operations) {
  const domains = uniqueDomains(operations);
  const imports = domains
    .map((domain) => {
      const factoryName = `create${toPascalCase(domain)}OpenApiQueryOptions`;
      return `import { ${factoryName} } from "@/query/v1/${domain}/options";`;
    })
    .join("\n");
  const spreads = domains
    .map(
      (domain) =>
        `    ...create${toPascalCase(domain)}OpenApiQueryOptions(client),`,
    )
    .join("\n");

  return `${generatedHeader(spec)}import {
  httpClient,
  type HttpClient,
} from "@/lib/http/client/http-client";
${imports}

export { openApiQueryKeys } from "@/query/v1/openapi-query-keys";

export function createOpenApiQueryOptions(client: HttpClient) {
  return {
${spreads}
  } as const;
}

export const openApiQueryOptions = createOpenApiQueryOptions(httpClient);
`;
}

function uniqueDomains(operations) {
  return Array.from(
    new Set(operations.map((operation) => operation.domain)),
  ).sort();
}

function renderRequestTypeImports(operations) {
  const importsByPath = new Map();

  operations
    .filter((operation) => operation.argsType)
    .forEach((operation) => {
      const sourcePath = `@/services/v1/${operation.domain}/types`;
      const imports = importsByPath.get(sourcePath) ?? new Set();
      imports.add(`${operation.typeName}Request`);
      importsByPath.set(sourcePath, imports);
    });

  return Array.from(importsByPath.entries())
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([sourcePath, imports]) => {
      const names = Array.from(imports).sort();
      return `import type {\n  ${names.join(",\n  ")},\n} from "${sourcePath}";`;
    })
    .join("\n");
}

function renderServiceImports(domain, operations) {
  const imports = operations.map((operation) => operation.name).sort();
  return `import {\n  ${imports.join(",\n  ")},\n} from "@/services/v1/${domain}/api";`;
}
