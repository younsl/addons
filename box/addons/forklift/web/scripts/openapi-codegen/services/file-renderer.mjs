import { apiBasePath } from "../config.mjs";
import { renderComponentType } from "../schema-renderer.mjs";

function generatedHeader(spec, source) {
  return `// This file is generated by scripts/openapi-codegen.mjs.
// Source: ${source}
// OpenAPI: ${spec.info?.title ?? "API"} ${spec.info?.version ?? ""}

`;
}

export function renderCommonTypesFile(spec) {
  return `${generatedHeader(spec, "src/openapi/openapi.yaml (repository root)")}${Object.entries(
    spec.components?.schemas ?? {},
  )
    .map(([name, schema]) => renderComponentType(name, schema))
    .join("\n")}`;
}

export function renderRuntimeFile(spec) {
  return `${generatedHeader(spec, "src/openapi/openapi.yaml (repository root)")}import {
  httpClient,
  type HttpClient,
  type RequestOptions,
} from "@/lib/http/client/http-client";

export type OpenApiPathValue = string | number | boolean;
export type OpenApiQueryValue = OpenApiPathValue | null | undefined;
export type OpenApiRequestOptions = RequestOptions & {
  client?: HttpClient;
};

export function resolveOpenApiRequestOptions(
  options?: OpenApiRequestOptions,
) {
  const { client = httpClient, ...requestOptions } = options ?? {};

  return {
    client,
    requestOptions,
  };
}

export function buildOpenApiPath(
  template: string,
  pathParams?: Record<string, OpenApiPathValue>,
) {
  if (!pathParams) return template;
  return template.replace(/\\{([^}]+)\\}/g, (_, name: string) =>
    encodeURIComponent(String(pathParams[name])),
  );
}

export function appendOpenApiQuery(
  pathname: string,
  query?: Record<string, OpenApiQueryValue>,
) {
  if (!query) return pathname;
  const searchParams = new URLSearchParams();
  for (const [name, value] of Object.entries(query)) {
    if (value === undefined || value === null) continue;
    searchParams.set(name, String(value));
  }
  const queryString = searchParams.toString();
  return queryString ? \`\${pathname}?\${queryString}\` : pathname;
}
`;
}

function findSchemaImports(source, schemaNames) {
  return Array.from(schemaNames)
    .filter((name) => new RegExp(`\\b${name}\\b`).test(source))
    .sort();
}

export function renderDomainTypesFile(spec, domain, operations, schemaNames) {
  const operationTypes = operations
    .map((operation) => {
      const response = `export type ${operation.typeName}Response = ${operation.responseType};`;
      if (!operation.argsType) return response;
      return `export type ${operation.typeName}Request = ${operation.argsType};\n${response}`;
    })
    .join("\n\n");
  const schemaImports = findSchemaImports(operationTypes, schemaNames);
  const importBlock =
    schemaImports.length > 0
      ? `import type {\n  ${schemaImports.join(",\n  ")}\n} from "../openapi-types";\n\n`
      : "";

  return `${generatedHeader(spec, "src/openapi/openapi.yaml (repository root)")}${importBlock}${operationTypes}
`;
}

function operationArgs(operation) {
  const requestParam = operation.argsType
    ? `params: ${operation.typeName}Request`
    : "";
  return [requestParam, "options?: OpenApiRequestOptions"]
    .filter(Boolean)
    .join(", ");
}

function renderServiceFunction(operation) {
  const pathArg = operation.hasPathParams ? "params.path" : "undefined";
  const queryArg = operation.hasQueryParams ? "params?.query" : "undefined";
  const bodyArg = operation.hasBody ? "params.body" : "undefined";
  const responseType = `${operation.typeName}Response`;
  const bodyType = operation.hasBody
    ? `${operation.typeName}Request["body"]`
    : "unknown";
  const args = operationArgs(operation);
  const routePath = operation.routePath.replace(apiBasePath, "${API_PREFIX}");
  const pathExpression = operation.hasPathParams
    ? `buildOpenApiPath(\`${routePath}\`, ${pathArg})`
    : `\`${routePath}\``;
  const urlExpression = operation.hasQueryParams
    ? `appendOpenApiQuery(${pathExpression}, ${queryArg})`
    : pathExpression;

  if (operation.method === "get") {
    return `export function ${operation.name}(${args}) {
  const { client, requestOptions } = resolveOpenApiRequestOptions(options);

  return client.get<${responseType}>(
    ${urlExpression},
    requestOptions,
  );
}`;
  }

  return `export function ${operation.name}(${args}) {
  const { client, requestOptions } = resolveOpenApiRequestOptions(options);

  return client.${operation.method}<${responseType}, ${bodyType}>(
    ${urlExpression},
    ${bodyArg},
    requestOptions,
  );
}`;
}

export function renderDomainServicesFile(spec, domain, operations) {
  const serviceFunctions = operations.map(renderServiceFunction).join("\n\n");
  const needsPathHelper = operations.some(
    (operation) => operation.hasPathParams,
  );
  const needsQueryHelper = operations.some(
    (operation) => operation.hasQueryParams,
  );
  const runtimeImports = [
    needsQueryHelper ? "appendOpenApiQuery" : null,
    needsPathHelper ? "buildOpenApiPath" : null,
    "resolveOpenApiRequestOptions",
    "type OpenApiRequestOptions",
  ].filter(Boolean);
  const typeImports = operations
    .flatMap((operation) => [
      operation.argsType ? `${operation.typeName}Request` : null,
      `${operation.typeName}Response`,
    ])
    .filter(Boolean)
    .sort();
  const runtimeImportBlock =
    runtimeImports.length > 0
      ? `import {\n  ${runtimeImports.join(",\n  ")},\n} from "@/services/v1/openapi-runtime";\n`
      : "";
  // The probes (/healthz, /readyz) sit outside the API prefix, so a domain made
  // up only of those interpolates nothing and must not import it.
  const prefixImportBlock = serviceFunctions.includes("${API_PREFIX}")
    ? `\nimport { API_PREFIX } from "@/services/paths";\n`
    : "";

  return `${generatedHeader(spec, "src/openapi/openapi.yaml (repository root)")}${runtimeImportBlock}${prefixImportBlock}
import type {
  ${typeImports.join(",\n  ")},
} from "./types";

${serviceFunctions}
`;
}
